"""Generate tests/golden/content.json: PySceneDetect's output on the synthetic clips.

Run by hand, not in CI, whenever tests/golden/clips.json changes:

    python -m venv .venv && .venv/bin/pip install scenedetect==0.7.3 opencv-python-headless
    .venv/bin/python scripts/make_goldens.py [path/to/ffmpeg]

The clips are generated from tests/golden/clips.json into a temporary folder (nothing is
committed but the numbers). For each clip it records, per frame, ContentDetector's `content_val`
and AdaptiveDetector's `adaptive_ratio (w=2)`, plus the cut frames of ContentDetector and
AdaptiveDetector with their defaults and `min_scene_len="0.6s"`.
"""
import csv
import json
import os
import shutil
import subprocess
import sys
import tempfile

import scenedetect
from scenedetect import SceneManager, StatsManager, open_video
from scenedetect.detectors import AdaptiveDetector, ContentDetector

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFMPEG = sys.argv[1] if len(sys.argv) > 1 else (
    os.path.join(os.environ["FFMPEG_DIR"], "bin", "ffmpeg") if "FFMPEG_DIR" in os.environ else "ffmpeg")


def detect(path, detector, metric):
    stats = StatsManager()
    manager = SceneManager(stats)
    manager.add_detector(detector)
    manager.detect_scenes(open_video(path, backend="opencv"))
    cuts = [start.frame_num for start, _ in manager.get_scene_list()[1:]]
    with tempfile.TemporaryDirectory() as d:
        csv_path = os.path.join(d, "stats.csv")
        stats.save_to_csv(csv_path)
        with open(csv_path, newline="") as f:
            rows = list(csv.DictReader(f))
    # "Frame Number" is 1-based in the stats file
    values = {int(r["Frame Number"]) - 1: float(r[metric]) for r in rows if r.get(metric) not in (None, "", "None")}
    return cuts, values


def main():
    spec = json.load(open(os.path.join(ROOT, "tests", "golden", "clips.json")))
    out = {
        "_comment": "Generated by scripts/make_goldens.py; do not edit by hand.",
        "pyscenedetect": scenedetect.__version__,
        "ffmpeg": subprocess.run([FFMPEG, "-version"], capture_output=True, text=True).stdout.split("\n")[0],
        "clips": {},
    }
    tmp = tempfile.mkdtemp()
    try:
        for clip in spec["clips"]:
            path = os.path.join(tmp, clip["name"] + ".mkv")
            subprocess.run([FFMPEG, "-v", "error", "-y", "-filter_complex", clip["graph"],
                            "-c:v", "ffv1", "-pix_fmt", "yuv444p", path], check=True)
            content_cuts, content_val = detect(path, ContentDetector(min_scene_len="0.6s"), "content_val")
            adaptive_cuts, ratio = detect(path, AdaptiveDetector(min_scene_len="0.6s"), "adaptive_ratio (w=2)")
            n = max(content_val) + 1
            out["clips"][clip["name"]] = {
                "frames": n,
                "content_val": [round(content_val.get(i, 0.0), 4) for i in range(n)],
                "adaptive_ratio": [round(ratio.get(i, 0.0), 4) for i in range(n)],
                "content_cuts": content_cuts,
                "adaptive_cuts": adaptive_cuts,
            }
            print(f"{clip['name']}: {n} frames, content cuts {content_cuts}, adaptive cuts {adaptive_cuts}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    with open(os.path.join(ROOT, "tests", "golden", "content.json"), "w") as f:
        json.dump(out, f, separators=(",", ":"))
        f.write("\n")


if __name__ == "__main__":
    main()
